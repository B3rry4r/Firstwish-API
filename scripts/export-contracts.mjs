#!/usr/bin/env node
// Writes contracts/firstwish-contracts.d.ts for the web app: the declarations of src/contracts/types.ts only.
// Types only: the file has no import and no runtime code, so the web app never imports the API.
import { execFileSync } from "node:child_process";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = mkdtempSync(join(tmpdir(), "fw-contracts-"));
try {
  const cfg = join(out, "tsconfig.json");
  writeFileSync(
    cfg,
    JSON.stringify({
      compilerOptions: { declaration: true, emitDeclarationOnly: true, strict: true, target: "ES2022", types: [], skipLibCheck: true, outDir: join(out, "d") },
      files: [join(ROOT, "src/contracts/types.ts")],
    }),
  );
  execFileSync(join(ROOT, "node_modules/.bin/tsc"), ["-p", cfg], { cwd: ROOT, stdio: ["ignore", "inherit", "inherit"] });
  const dts = readFileSync(join(out, "d", "types.d.ts"), "utf8");
  if (/^\s*import\s|require\(/m.test(dts)) throw new Error("contracts must not import anything");
  const sha = JSON.parse(readFileSync(join(ROOT, ".pipeline/registry.lock.json"), "utf8")).registrySha256;
  const head = `// Firstwish API contracts for the web app. Generated by \`npm run contracts:export\`; do not edit.\n// Registry sha256 ${sha}.\n`;
  mkdirSync(join(ROOT, "contracts"), { recursive: true });
  writeFileSync(join(ROOT, "contracts/firstwish-contracts.d.ts"), head + dts);
  console.log("wrote contracts/firstwish-contracts.d.ts");
} finally {
  rmSync(out, { recursive: true, force: true });
}
