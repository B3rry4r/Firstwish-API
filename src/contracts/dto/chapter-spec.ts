// Request validation for chapter-spec endpoints. Kept by hand with each registry reopen (the generator is retired; scripts/check-contracts.mjs guards it).
import { IsInt, IsOptional, IsString, Max, Min } from "class-validator";
import { Type } from "class-transformer";
import type { GetChapterSpecsQuery } from "../types";

/** E-28 GET /v1/chapter-specs (query). */
export class GetChapterSpecsQueryDto implements GetChapterSpecsQuery {
  @IsOptional()
  @IsString()
  cursor?: string;
  @IsOptional()
  @Type(() => Number)
  @IsInt()
  @Min(1)
  @Max(50)
  limit?: number;
}
